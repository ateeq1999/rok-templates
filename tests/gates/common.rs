//! Helpers the gates share.

use std::path::{Path, PathBuf};
use std::process::Command;

/// The template directory `dir` (such as `axum-api`) of this crate.
pub(crate) fn template_dir(dir: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("templates")
        .join(dir)
}

/// `cargo <args>` in the crate at `dir`. Every crate that compiles generated
/// code builds into one shared target directory, so its dependencies are
/// built once.
///
/// Incremental compilation is off: several gates build in that directory
/// at once, and an interrupted or concurrent build can leave a corrupt
/// incremental cache whose `warning:` fails a gate that demands a clean
/// build. These one-shot builds gain nothing from the cache anyway.
pub(crate) fn cargo(dir: &Path, args: &[&str]) -> Command {
    let mut command = Command::new("cargo");
    command
        .args(args)
        .current_dir(dir)
        .env(
            "CARGO_TARGET_DIR",
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("target/fixture-target"),
        )
        .env("CARGO_INCREMENTAL", "0");
    command
}

/// A path the way `rok sqlc` prints one outside the current directory: `/`
/// as the separator on every platform.
pub(crate) fn shown(path: &Path) -> String {
    path.display().to_string().replace('\\', "/")
}

/// Generated code targets SQLx 0.9, whose minimum Rust version is above the
/// tool's own. Returns why a gate that builds a project must skip on the
/// current toolchain, or `None` when the toolchain meets the floor the
/// project declares in its `rust-version`.
pub(crate) fn generated_code_skip_reason(project: &Path) -> Option<String> {
    let manifest: toml::Table = std::fs::read_to_string(project.join("Cargo.toml"))
        .expect("read the project's Cargo.toml")
        .parse()
        .expect("parse the project's Cargo.toml");
    let floor = manifest["package"]["rust-version"]
        .as_str()
        .expect("the project declares package.rust-version")
        .to_owned();
    let rustc = std::env::var("RUSTC").unwrap_or_else(|_| "rustc".into());
    let output = Command::new(rustc)
        .arg("--version")
        .output()
        .expect("run rustc --version");
    let version = String::from_utf8_lossy(&output.stdout);
    // "rustc 1.94.0 (...)"
    let current = version
        .split_whitespace()
        .nth(1)
        .expect("rustc --version prints a version")
        .to_owned();
    if parse(&current) >= parse(&floor) {
        None
    } else {
        Some(format!(
            "this project needs rustc {floor}; the toolchain is {current}"
        ))
    }
}

fn parse(version: &str) -> (u32, u32, u32) {
    let parts: Vec<u32> = version
        .trim_end_matches(|c: char| !c.is_ascii_digit())
        .split('.')
        .filter_map(|p| p.parse().ok())
        .collect();
    (
        *parts.first().unwrap_or(&0),
        *parts.get(1).unwrap_or(&0),
        *parts.get(2).unwrap_or(&0),
    )
}

/// Whether `text` looks like a generated file (first line carries the
/// generated marker of either the current or the legacy generator).
pub(crate) fn is_generated(text: &str) -> bool {
    let first = text.lines().next().unwrap_or("");
    first.contains("@generated by rok-data-sqlc") || first.contains("@generated by rok-sqlc")
}

/// With `ROK_DATA_PATH` set, redirects the project's `rok-data` from
/// crates.io to that checkout's `crates/rok-data`, so the runtime matches
/// the generator; without it the project builds against crates.io.
pub(crate) fn rok_data_patch_shim(dir: &Path) -> std::io::Result<()> {
    let Some(checkout) = std::env::var_os("ROK_DATA_PATH") else {
        return Ok(());
    };
    // TOML basic strings escape backslashes; forward slashes work everywhere.
    let runtime = Path::new(&checkout)
        .join("crates/rok-data")
        .to_string_lossy()
        .replace('\\', "/");
    let replacements = format!("[patch.crates-io]\nrok-data = {{ path = \"{runtime}\" }}\n");
    let config = dir.join(".cargo/config.toml");
    std::fs::create_dir_all(config.parent().expect("a parent"))?;
    std::fs::write(&config, replacements)?;
    Ok(())
}
